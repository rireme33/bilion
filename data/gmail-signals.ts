function buildCodexPrompt(input: {
  productName: string;
  buyer: string;
  paidPain: string;
  firstOffer: string;
  price: string;
  starterProduct: string;
}) {
  return [
    `Build a mobile-first MVP for ${input.productName}.`,
    "",
    `Target buyer: ${input.buyer}`,
    `Paid pain: ${input.paidPain}`,
    `First offer and price: ${input.firstOffer} at ${input.price}`,
    `MVP scope: ${input.starterProduct}`,
    "",
    "What not to build:",
    "- Do not build a full platform.",
    "- Do not add auth, billing, integrations, or external APIs.",
    "- Do not build beyond the manual first offer until buyers reply.",
    "",
    "Build constraints:",
    "- Next.js / React.",
    "- Mobile-first.",
    "- Local state only.",
    "- Mock data allowed.",
    "- Clean dark SaaS UI.",
    "- Include copyable output.",
    "- Include pricing CTA.",
    "- Include a Build only after replies validation note.",
  ].join("\n");
}

