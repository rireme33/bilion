function compact(value: string, maxLength = 180) {
  const cleanValue = value.replace(/\s+/g, " ").trim();

  if (cleanValue.length <= maxLength) {
    return cleanValue;
  }

  const sentence = cleanValue
    .split(/(?<=[.!?])\s+/)
    .find((item) => item.length > 24 && item.length <= maxLength);

  if (sentence) {
    return sentence;
  }

  const words = cleanValue.split(" ");
  let nextValue = "";

  for (const word of words) {
    const candidate = nextValue ? `${nextValue} ${word}` : word;

    if (candidate.length > maxLength) {
      break;
    }

    nextValue = candidate;
  }

  return nextValue || cleanValue.slice(0, maxLength).trim();
}

function scoreTextSpecificity(value: string, goodLength: number) {
  const cleanValue = value.trim();
  let score = 4;

  if (cleanValue.length >= goodLength) {
    score += 2;
  }

  if (/\d|\$|USD|JPY|month|week|daily|hour|client|owner|operator/i.test(cleanValue)) {
    score += 1.5;
  }

  if (/,| and | with | for | at /i.test(cleanValue)) {
    score += 1;
  }

  if (/not extracted|generic|someone|people|users/i.test(cleanValue)) {
    score -= 1.5;
  }

  return Math.max(1, Math.min(10, Math.round(score)));
}

function scoreHook(body: string) {
  const [firstLine = ""] = body.split("\n");
  let score = 4;

  if (firstLine.length >= 28 && firstLine.length <= 120) {
    score += 2;
  }

  if (/stop|boring|paying|paid|random|before building|tiny|money move|test/i.test(firstLine)) {
    score += 2;
  }

  if (firstLine.includes("?") || firstLine.includes(":")) {
    score += 0.5;
  }

  if (/Money Move:/i.test(firstLine)) {
    score -= 3;
  }

  return Math.max(1, Math.min(10, Math.round(score)));
}

function scoreCta(body: string) {
  const ctaLine = body.split("\n").slice(-2).join(" ");
  let score = 4;

  if (/Bilion/i.test(ctaLine)) {
    score += 2;
  }

  if (/Build\/Sell\/Post|Codex|money moves|signal/i.test(ctaLine)) {
    score += 2;
  }

  if (ctaLine.length >= 18 && ctaLine.length <= 95) {
    score += 1;
  }

  return Math.max(1, Math.min(10, Math.round(score)));
}

function getReadiness(overall: number): ReadinessStatus {
  if (overall >= 8) {
    return "Ready";
  }

  if (overall >= 6) {
    return "Needs Work";
  }

  return "Skip";
}

function getQualityScores(record: ContentStudioRecord, body: string): QualityScores {
  const scores = {
    buyerSpecificity: scoreTextSpecificity(record.buyer, 65),
    cta: scoreCta(body),
    hook: scoreHook(body),
    paidPain: scoreTextSpecificity(record.pain, 85),
    tinyOffer: scoreTextSpecificity(`${record.firstProduct} ${record.price}`, 55),
  };
  const entries = Object.entries(scores) as Array<[QualityField, number]>;
  const [lowestField] = entries.reduce((lowest, entry) =>
    entry[1] < lowest[1] ? entry : lowest,
  );
  const overall =
    Math.round(
      (scores.hook +
        scores.buyerSpecificity +
        scores.paidPain +
        scores.tinyOffer +
        scores.cta) *
        2,
    ) / 10;

  return {
    ...scores,
    lowestField,
    overall,
    readiness: getReadiness(overall),
  };
}

function classifyPerformance(state: CardState): PerformanceStatus {
  const clicks = state.clicks || 0;
  const impressions = state.impressions || 0;
  const likes = state.likes || 0;
  const replies = state.replies || 0;

  if (replies > 0 || clicks > 0) {
    return "winner";
  }

  if (impressions >= 500 && likes + replies + clicks <= 2) {
    return "maybe";
  }

  if (impressions > 0 && impressions < 500 && likes + replies + clicks === 0) {
    return "loser";
  }

  return state.status || state.winner || "";
}

