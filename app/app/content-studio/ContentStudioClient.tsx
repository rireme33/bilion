function pickByIndex<T>(items: readonly T[], index: number) {
  return items[index % items.length];
}

function getCta(ctaLevel: CtaLevel, index: number) {
  if (ctaLevel === "Auto") {
    return pickByIndex(ctaVariants, index);
  }

  return ctaCopy[ctaLevel].endsWith(".") ? ctaCopy[ctaLevel] : `${ctaCopy[ctaLevel]}.`;
}

function withCta(body: string, ctaLevel: CtaLevel, index: number) {
  return `${body}\n\n${getCta(ctaLevel, index)}`;
}

function getPattern(index: number) {
  return pickByIndex(contentPatterns, index);
}

